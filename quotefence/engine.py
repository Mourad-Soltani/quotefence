"""Rule-based quote fence engine. No network, no LLM required."""

from __future__ import annotations

import re
from dataclasses import dataclass, field

RISK_PATTERNS: list[tuple[str, str, str]] = [
    (r"\betc\.?\b", "open-ended", "The brief uses 'etc.' which leaves the deliverable list unbounded."),
    (r"\band so on\b", "open-ended", "The brief trails off with 'and so on'."),
    (r"\bunlimited\b", "unlimited-work", "Unlimited revisions or hours will erase your margin."),
    (r"\bas needed\b", "open-ended", "'As needed' is not a scoped quantity."),
    (r"\basap\b", "timeline", "ASAP is not a date. Put a calendar deadline in the quote."),
    (r"\bas soon as possible\b", "timeline", "Replace ASAP language with a named date."),
    (r"\bmake it pop\b", "subjective", "Subjective design language has no acceptance test."),
    (r"\bworld[- ]class\b", "subjective", "Subjective quality language is unmeasurable."),
    (r"\bongoing support\b", "retainer-leak", "Ongoing support should be a separate retainer, not bundled."),
    (r"\ball pages\b", "unbounded-pages", "Specify an exact page or screen count."),
    (r"\bwhatever it takes\b", "open-ended", "This phrase waives every boundary."),
    (r"\bfix anything\b", "open-ended", "Unbounded bug/fix language."),
]


@dataclass
class RiskFlag:
    code: str
    message: str
    snippet: str


@dataclass
class QuoteFence:
    title: str
    included: list[str]
    excluded: list[str]
    assumptions: list[str]
    validity_days: int
    change_order: str
    risks: list[RiskFlag] = field(default_factory=list)
    risk_score: int = 0

    def to_markdown(self) -> str:
        lines = [
            f"# Quote: {self.title}",
            "",
            f"_Valid for {self.validity_days} days from issue date._",
            "",
            "## Included",
        ]
        lines.extend(f"- {item}" for item in self.included)
        lines.extend(["", "## Excluded"])
        lines.extend(f"- {item}" for item in self.excluded)
        lines.extend(["", "## Assumptions"])
        lines.extend(f"- {item}" for item in self.assumptions)
        lines.extend(["", "## Change orders", self.change_order, ""])
        if self.risks:
            lines.append("## Risk flags (internal)")
            for risk in self.risks:
                lines.append(f"- [{risk.code}] {risk.message}")
            lines.append("")
        lines.append(f"Risk score: {self.risk_score}/100")
        lines.append("")
        lines.append("— Generated by QuoteFence · Mourad.Soltani")
        return "\n".join(lines)


def _sentences(text: str) -> list[str]:
    parts = re.split(r"[.\n;]+", text)
    return [p.strip() for p in parts if p.strip()]


def scan_risks(brief: str) -> list[RiskFlag]:
    flags: list[RiskFlag] = []
    lower = brief.lower()
    for pattern, code, message in RISK_PATTERNS:
        match = re.search(pattern, lower, flags=re.IGNORECASE)
        if match:
            flags.append(RiskFlag(code=code, message=message, snippet=match.group(0)))
    return flags


def score_risks(flags: list[RiskFlag]) -> int:
    if not flags:
        return 8
    raw = min(100, 18 + 14 * len(flags))
    return raw


def fence_quote(
    brief: str,
    title: str = "Untitled engagement",
    validity_days: int = 14,
) -> QuoteFence:
    if not brief or not brief.strip():
        raise ValueError("brief is required")
    if validity_days < 1 or validity_days > 90:
        raise ValueError("validity_days must be between 1 and 90")

    risks = scan_risks(brief)
    sentences = _sentences(brief)
    included = sentences[:6] or ["Discovery call and written scope confirmation"]
    excluded = [
        "Work not listed in Included",
        "Third-party licenses, ads, or stock beyond the named budget",
        "Unlimited revision rounds",
        "Post-launch retainers unless quoted separately",
    ]
    assumptions = [
        "Client provides content and access within 3 business days of request.",
        "One decision-maker is named for approvals.",
        "Feedback arrives in one consolidated batch per round.",
    ]
    change_order = (
        "Work outside Included requires a written change order with price and "
        "new delivery date before work starts."
    )
    return QuoteFence(
        title=title.strip() or "Untitled engagement",
        included=included,
        excluded=excluded,
        assumptions=assumptions,
        validity_days=validity_days,
        change_order=change_order,
        risks=risks,
        risk_score=score_risks(risks),
    )
